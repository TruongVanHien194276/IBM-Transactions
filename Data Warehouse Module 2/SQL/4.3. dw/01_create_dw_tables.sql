/*
Tạo dimension, fact, ETL audit và staging objects

Quy ước:
- Surrogate/unknown key = -1
- fact_transaction grain = 1 dòng raw.transactions
- fact_pattern_transaction grain = 1 transaction trong 1 laundering attempt
- Fact lớn không khai báo FK vật lý để tối ưu bulk load; integrity được kiểm soát
  bằng ETL lookup + etl.validate_dw()
*/

