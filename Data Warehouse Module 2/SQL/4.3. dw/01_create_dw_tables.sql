CREATE OR REPLACE VIEW stg.v_transaction_enriched AS
SELECT
    t.*,
    to_char(t.transaction_timestamp, 'YYYYMMDD')::INTEGER AS date_key,
    to_char(t.transaction_timestamp, 'HH24MI')::INTEGER AS time_key,
    t.from_bank_id <> t.to_bank_id AS is_cross_bank,
    t.payment_currency <> t.receiving_currency AS is_cross_currency,
    t.from_bank_id = t.to_bank_id
        AND t.from_account_id = t.to_account_id AS is_self_transfer,
    CASE
        WHEN t.payment_currency <> t.receiving_currency AND t.amount_paid > 0
            THEN (t.amount_received / t.amount_paid)::NUMERIC(38,12)
        ELSE NULL
    END AS implied_exchange_rate
FROM raw.transactions t;

CREATE OR REPLACE VIEW stg.v_pattern_enriched AS
SELECT
    p.*,
    to_char(p.transaction_timestamp, 'YYYYMMDD')::INTEGER AS date_key,
    to_char(p.transaction_timestamp, 'HH24MI')::INTEGER AS time_key
FROM raw.laundering_pattern_transaction p;

