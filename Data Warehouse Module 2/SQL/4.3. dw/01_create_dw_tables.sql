-- Sinh đủ 1.440 phút trong ngày; time_key dùng dạng HHMM.
INSERT INTO dw.dim_time (time_key, time_value, hour_number, minute_number, day_part)
SELECT
    (extract(hour FROM tm)::INTEGER * 100 + extract(minute FROM tm)::INTEGER),
    tm::TIME,
    extract(hour FROM tm)::SMALLINT,
    extract(minute FROM tm)::SMALLINT,
    CASE
        WHEN extract(hour FROM tm) BETWEEN 5 AND 11 THEN 'Morning'
        WHEN extract(hour FROM tm) BETWEEN 12 AND 16 THEN 'Afternoon'
        WHEN extract(hour FROM tm) BETWEEN 17 AND 21 THEN 'Evening'
        ELSE 'Night'
    END
FROM generate_series(
    TIMESTAMP '2000-01-01 00:00:00',
    TIMESTAMP '2000-01-01 23:59:00',
    INTERVAL '1 minute'
) AS g(tm)
ON CONFLICT (time_key) DO NOTHING;

